import { LAB_REVIEW, type Archetype } from './schemas'

/** Dimensions are fictitious teaching specimens, provided by the parameter registry. */
function specimen(
  id: string,
  label: string,
  family: Archetype['family'],
  shape: Archetype['shape'],
  features: string[],
  orientation: string,
  containment: string,
  pathways: Archetype['pathways'],
  risks: string[],
): Archetype {
  return {
    id,
    label,
    family,
    shape,
    dimensionsParam: [`archetype.${id}.length`, `archetype.${id}.width`, `archetype.${id}.depth`],
    features,
    orientation,
    containment,
    pathways,
    risks,
    sourceIds: ['histology-guide', 'leica-101-histology', 'hq-original', 'cap-nsh-2025'],
    review: {
      ...LAB_REVIEW,
      verification:
        'Original teaching archetype informed by public microanatomy and general histology preparation guidance. Specimen-specific allocation and orientation require qualified review. CAP/NSH is listed as further reading only and was not accessed; no claim is made that these instructions were checked against that document.',
    },
  }
}
