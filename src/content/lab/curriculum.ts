function level(
  id: CareerLevel['id'],
  title: string,
  description: string,
  theory: string[],
  practical: CareerLevel['practical'],
): CareerLevel {
  return {
    id,
    title,
    description,
    boundary: `${LEARNING_BOUNDARY} ${SCOPE_BOUNDARY}`,
    competencies: COMPETENCIES.filter((c) => c.level === id).map((c) => c.id),
    theory,
    practical,
    sourceIds: ['hq-original', 'ascp-cg-2026'],
    review: LAB_REVIEW,
  }
}
