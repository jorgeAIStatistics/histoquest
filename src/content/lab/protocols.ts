const rinse = (id = 'wash'): Step => [
  id,
  'Rinse',
  'Method-specified water',
  'wash',
  'Remove carryover before the next reaction.',
]
function graph(id: string, steps: Step[]): StainProtocol['steps'] {
  return steps.map(([stepId, label, reagent, action, note], index) => ({
    id: stepId,
    label,
    reagent,
    action,
    note,
    durationParam: `protocol.${id}.${stepId}.minutes`,
    dependencies: index ? [steps[index - 1][0]] : [],
  }))
}
function protocol(
  id: string,
  label: string,
  target: string,
  principle: string,
  result: string,
  chemistry: Step[],
  controls: string[],
  failure: StainProtocol['failures'][number],
  source: string,
  options: {
    pathway?: StainProtocol['pathway']
    aqueous?: boolean
    customPrep?: Step[]
    customFinish?: Step[]
  } = {},
): StainProtocol {
  return {
    id,
    label,
    target,
    principle,
    result,
    pathway: options.pathway ?? 'paraffin',
    mounting: options.aqueous ? 'aqueous' : 'resinous',
    steps: graph(id, [
      ...(options.customPrep ?? prep),
      ...chemistry,
      ...(options.customFinish ?? finish),
    ]),
    controls,
    failures: [failure],
    sourceIds: [source],
    review: LAB_REVIEW,
  }
}
